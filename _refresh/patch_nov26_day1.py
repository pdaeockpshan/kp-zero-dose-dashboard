"""Register SNID Nov 2026 and carry its campaign-day-1 portal readings into the campaign pages.

The portal posts four district tables from campaign day 1: the coverage summary (admin coverage),
Intra Campaign Monitoring (Cluster) (the ICM house/cluster instrument), the operational-issue report
and Supervisor Monitoring. The dashboard's campaign registry `CQ` had no Nov entry, so every campaign
view opened on Sept-26 and the admin coverage columns were empty for the round now under way.

What this patch does, in one pass on the master only:

- unshifts NOV-26-1 / "SNID Nov 2026" to the front of `CQ.camps`, so the registry opens on the live
  round, and stores the four day-1 tables beside the existing campaign payloads:
  `CQ.adm` (the 11 coverage-summary fields per district), `CQ.icm` (the 22 cluster fields plus the
  operational-issue % and the 10 supervisor checklist percentages) and `CQ.meta` (campaign day,
  read date and source routes).
- teaches `cqDist` to build the admin coverage row from `CQ.adm` when the missed-children register
  has no UC rows for that campaign, so the post-campaign admin columns compute for Nov.
- adds the operational-issue column to the cluster table and two district tables: admin coverage
  (11 fields) and supervisor cluster monitoring (10 checklist items), each with its own CSV.
- empties the fake one-district Nov seed in `ICMQ` (DIKHAN, one team, all 100%) so the intra-campaign
  page shows its designed "no UC-level export" state instead of a fabricated district.
- adds Nov's supervisor checklist percentages to `NOCD`, so the ops-vs-outcome table and scatter
  carry the day-1 checklist / teams-supported values.
- guards the two places that assumed `CQ.camps[0]` is Sept-26 (the district brief and province
  comparators) and makes the pre-campaign page fall back to the NEAP live card when the selected
  campaign has no pre-campaign block.

Values are exactly what the portal returned on 02-Nov-2026 for campaign day 1; no figure is inferred.
Master only; the three other variants are regenerated by push_master.py.
"""
