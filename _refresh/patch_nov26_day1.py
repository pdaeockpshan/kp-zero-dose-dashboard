RENAME = {'WAZIR-S LOWER': 'WAZIR-S Lower', 'WAZIR-S UPPER': 'WAZIR-S Upper'}


def crlf(s):
    return s.replace('\n', '\r\n')


EDITS = []


def edit(old, new, note):
    EDITS.append((crlf(old), crlf(new), note))


def norm(d):
    return RENAME.get(d, d)


def build_payloads():
    raw = json.load(open(DATA, encoding='utf-8'))
    camp = raw['campaign']
    if camp['v'] != CAMPAIGN or camp['l'] != LABEL:
        raise SystemExit('unexpected campaign in the data file: %r' % (camp,))

    adm_keys = ['kidsHH', 'housesP', 'housesV', 'target', 'vacc', 'cov', 'na', 'ref', 'missed', 'mobile', 'waste']
    adm = {}
    for d, v in raw['adm'].items():
        if len(v) != len(adm_keys):
            raise SystemExit('adm row width %d for %s' % (len(v), d))
        adm[norm(d)] = dict(zip(adm_keys, v))

    icm = {}
    for d, v in raw['icm'].items():
        if len(v) != len(raw['icmKeys']):
            raise SystemExit('icm row width %d for %s' % (len(v), d))
        row = dict(zip(raw['icmKeys'], v))
        row['op'] = raw['op'].get(d)
        row['sv'] = raw['sv'].get(d)
        icm[norm(d)] = row

    sv = {norm(d): v for d, v in raw['sv'].items()}

    if not (len(adm) == len(icm) == len(sv) == 27):
        raise SystemExit('district counts disagree: adm %d icm %d sv %d' % (len(adm), len(icm), len(sv)))
    if set(adm) != set(icm) or set(icm) != set(sv):
        raise SystemExit('district names disagree between tables')
    if sorted(adm) != sorted(norm(d) for d in raw['adm']):
        raise SystemExit('a rename collided with an existing district')
    if len(raw['op']) != 20:
        raise SystemExit('operational-issue table should list 20 districts, got %d' % len(raw['op']))
    for d, a in adm.items():
        if a['vacc'] > a['target']:
            raise SystemExit('%s vaccinated above target on day 1' % d)
        if not (0 <= a['cov'] <= 100):
            raise SystemExit('%s coverage outside 0-100' % d)

    meta = {
        'day': camp['day'],
        'start': camp['start'],
        'asof': '02-Nov-2026',
        'read': camp['read'],
        'src': raw['src'],
    }

    sp = {}
    for d, v in sv.items():
        if v[7] is not None and v[8] is not None:
            sp[d] = {'chk': v[7], 'sup': v[8]}

    return adm, icm, meta, sp


