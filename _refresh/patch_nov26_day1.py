def main():
    cfg, vs = dashpatch.load_variants()
    v = next(x for x in vs if x.rel == 'index.html')

    cq = json.loads(dashpatch.get_payload(v.text, 'CQ'))
    if any(c.get('v') == CAMPAIGN for c in cq.get('camps') or []):
        print('nothing to do: %s already registered' % CAMPAIGN)
        return

    # --- CQ: register the round and add the four day-1 tables
    camps = [c for c in cq['camps'] if c.get('v') != CAMPAIGN]
    cq['camps'] = [{'v': CAMPAIGN, 'l': LABEL}] + camps
    cq.setdefault('icm', {})[CAMPAIGN] = ICM
    cq['adm'] = {CAMPAIGN: ADM}
    cq['meta'] = {CAMPAIGN: META}
    cq_json = srcutil.dumps(cq)
    reloaded = json.loads(cq_json.replace('<\\/', '</'))
    assert reloaded['camps'][1:] == camps
    assert reloaded['pre'] == cq['pre']
    for k in ('SEP-26-1', 'MAY-26-1', 'APR-26-1'):
        assert reloaded['icm'][k] == cq['icm'][k], 'round trip lost %s' % k
    assert len(reloaded['icm'][CAMPAIGN]) == 27
    assert len(reloaded['adm'][CAMPAIGN]) == 27
    dashpatch.swap_payload(v, 'CQ', cq_json)

    # --- ICMQ: remove the fabricated one-district Nov seed, keep the label so the picker can say
    # that no UC-level export is embedded for this round
    icmq = json.loads(dashpatch.get_payload(v.text, 'ICMQ'))
    before = {k: json.loads(json.dumps(val)) for k, val in icmq['camps'].items() if k != LABEL}
    icmq['camps'][LABEL] = {'wt': {}, 'n': {}}
    icmq_json = srcutil.dumps(icmq)
    re_icm = json.loads(icmq_json.replace('<\\/', '</'))
    assert re_icm['camps'][LABEL] == {'wt': {}, 'n': {}}
    assert {k: re_icm['camps'][k] for k in before} == before, 'round trip lost a monitoring round'
    dashpatch.swap_payload(v, 'ICMQ', icmq_json)

    # --- NOCD: supervisor checklist percentages for the ops-vs-outcome table
    nocd = json.loads(dashpatch.get_payload(v.text, 'NOCD'))
    before_n = {k: json.loads(json.dumps(val)) for k, val in nocd['camps'].items()}
    nocd['camps'][LABEL] = {'sp': SP}
    nocd_json = srcutil.dumps(nocd)
    re_n = json.loads(nocd_json.replace('<\\/', '</'))
    assert re_n['camps'][LABEL] == {'sp': SP}
    assert {k: re_n['camps'][k] for k in before_n} == before_n, 'round trip lost a monitors round'
    dashpatch.swap_payload(v, 'NOCD', nocd_json)

    # --- text edits
    for old, new, note in EDITS:
        v.require(v.text.count(old) == 1, 'anchor %r found %d times' % (note, v.text.count(old)))
        v.text = v.text.replace(old, new, 1)
        v.changes.append(note)

    dashpatch.assert_crlf(v)
    dashpatch.write_variants([v])
    print('PATCHED index.html %+d chars, %d payloads + %d edits' %
          (v.delta(), 3, len(EDITS)))
    print('  districts: admin %d, cluster %d, supervisor %d; operational issues %d' %
          (len(ADM), len(ICM), len(SP), sum(1 for r in ICM.values() if r['op'] is not None)))


if __name__ == '__main__':
    main()
