"""Read the reworked district sheet, which now files one tab per campaign day.

The desk replaced the single Live tab with Day-1st .. Day-5th because districts kept typing into
another district's row. Each tab still carries the same 26 columns and its own Campaign day, so the
parser is unchanged; what changes is the reader:

- mdpFeedSrcs() lists every day tab beside the form, and each source carries the day it belongs to.
- A day tab arrives with all 27 rows prefilled (time, plan, day), so a row counts only once a
  reported or deployed count is typed. Timestamp and planned no longer prove a filing - keeping
  either in the test would turn four empty tabs into 108 districts at 0%.
- gviz answers a sheet name it does not know with the first tab's rows. A tab whose rows all name a
  different day is therefore refused rather than read as that day. The same fallback is what the
  Blockers read sees when that tab is renamed or deleted, so its error message names the tab.

Master only; the three other variants are regenerated by push_master.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dashpatch


def crlf(s):
    return s.replace('\n', '\r\n')


EDITS = []


def edit(old, new, note):
    EDITS.append((crlf(old), crlf(new), note))


# 1. the source list
edit(
    " gridTab:'Live',\n"
    " gridBlock:'Blockers',\n",
    " // One gviz tab per campaign day, as the desk now files it. Google answers a sheet name it does\n"
    " // not know with the first tab's rows, so mdpFeedParse checks each row's typed day against the\n"
    " // tab it sits in and refuses a tab whose rows all name another day. A new day tab goes here.\n"
    " gridTabs:[['Day-1st',1],['Day-2nd',2],['Day-3rd',3],['Day-4th',4],['Day-5th',5]],\n"
    " gridBlock:'Blockers',\n",
    'MDP_FEED: five day tabs instead of Live')

# 2. one source per day tab, each carrying its day
edit(
    " if(MDP_FEED.gridId)s.push({k:'grid',id:MDP_FEED.gridId,tab:MDP_FEED.gridTab,l:'sheet'});\n",
    " if(MDP_FEED.gridId)(MDP_FEED.gridTabs||[]).forEach(t=>s.push({k:'grid',id:MDP_FEED.gridId,\n"
    "  tab:t[0],day:t[1],l:t[0]}));\n",
    'mdpFeedSrcs: emit every day tab')

# 3. parser state
edit(
    " const rows={};let miss=0,sup=0,blank=0,unk=0;\n"
    " if(!ix.n||!ix.day)return {rows:rows,n:0,miss:0,sup:0,unk:0,badHdr:1};\n"
    " const grid=!!(opt&&opt.grid);\n",
    " const rows={};let miss=0,sup=0,blank=0,unk=0,offd=0,onday=0,got=0;\n"
    " if(!ix.n||!ix.day)return {rows:rows,n:0,miss:0,sup:0,unk:0,badHdr:1};\n"
    " const grid=!!(opt&&opt.grid),td=opt&&opt.day?Math.round(opt.day):0;\n",
    'mdpFeedParse: tab day state')

# 4. day comes from the tab; a mismatched typed day is counted
edit(
    "  const jd=pick(ix.day,r),day=jd!=null?Math.round(mdpNumV(r[jd])):0;\n"
    "  if(!(day>=1)||day>MDP_MAXD){miss++;continue;}\n",
    "  const jd=pick(ix.day,r),typed=jd!=null?Math.round(mdpNumV(r[jd])):0;\n"
    "  // The tab names the day. A row whose typed day disagrees stays with its tab, and the count is\n"
    "  // reported so the desk can see that somebody filed in the wrong place.\n"
    "  const day=td||typed;\n"
    "  if(!(day>=1)||day>MDP_MAXD){miss++;continue;}\n"
    "  if(td&&typed>=1&&typed<=MDP_MAXD){if(typed===td)onday++;else{offd++;if(!got)got=typed;}}\n",
    'mdpFeedParse: day from the tab')

# 5. a prefilled row is not a filing
edit(
    "  if(grid&&!hasV(ix.ts,r)&&!hasV(ix.ucp,r)&&!hasV(ix.ucr,r)&&!hasV(ix.inc,r)&&!hasV(ix.why,r)\n"
    "   &&!MDP_TYPES.some((x,k)=>hasV(ix['p'+k],r)||hasV(ix['d'+k],r))){blank++;continue;}\n",
    "  // A prefilled row is not a filing: every day tab arrives with a time and a plan on all 27 rows,\n"
    "  // and a copied tab leaves stray zeros behind. A row counts when the district has reported UCs\n"
    "  // (a typed 0 there is a real return), deployed a team, recorded an incident or written a reason.\n"
    "  const posCol=j=>{const i=pick(j,r);return i!=null&&String(r[i]).trim()!==''&&mdpNumV(r[i])>0;};\n"
    "  if(grid&&!hasV(ix.ucr,r)&&!posCol(ix.inc)&&!hasV(ix.why,r)\n"
    "   &&!MDP_TYPES.some((x,k)=>posCol(ix['d'+k]))){blank++;continue;}\n",
    'mdpFeedParse: require a real count, not a prefilled row')

# 6. refuse a tab that Google did not honour
edit(
    " return {rows:rows,n:Object.keys(rows).length,miss:miss,sup:sup,blank:blank,unk:unk};\n",
    " // A renamed or deleted tab is answered with the first tab's rows. If every row names another\n"
    " // day, this is not that day's tab and reading it would file one day's numbers under another.\n"
    " if(td&&offd&&!onday)return {rows:{},n:0,miss:miss,sup:0,unk:0,offd:offd,badTab:1,got:got};\n"
    " return {rows:rows,n:Object.keys(rows).length,miss:miss,sup:sup,blank:blank,unk:unk,offd:offd};\n",
    'mdpFeedParse: refuse a tab serving another day')

# 7. loader: pass the tab day, count grid reads and wrong-day rows
edit(
    " const srcs=mdpFeedSrcs(),all={},errs=[],ok=[];\n"
    " let miss=0,sup=0; for(const s of srcs){\n",
    " const srcs=mdpFeedSrcs(),all={},errs=[],ok=[];\n"
    " let miss=0,sup=0,offd=0,gok=0,gtot=0;\n"
    " for(const s of srcs){\n"
    "  if(s.k==='grid')gtot++;\n",
    'mdpFeedLoad: count day tabs')

edit(
    "   const o=mdpFeedParse(t,{grid:s.k==='grid'});\n"
    "   if(o.badHdr)throw new Error('the District and Campaign day columns are missing');\n"
    "   ok.push(s.l);miss+=o.miss;sup+=o.sup||0;\n",
    "   const o=mdpFeedParse(t,{grid:s.k==='grid',day:s.day});\n"
    "   if(o.badHdr)throw new Error('the District and Campaign day columns are missing');\n"
    "   if(o.badTab)throw new Error('the tab is not there - Google served campaign day '+o.got\n"
    "    +' rows from its first tab instead');\n"
    "   ok.push(s.l);miss+=o.miss;sup+=o.sup||0;offd+=o.offd||0;\n"
    "   if(s.k==='grid')gok++;\n",
    'mdpFeedLoad: read the tab day, refuse a wrong tab')

# 8. provenance line: form + sheet, plus how many day tabs answered
edit(
    "  MDLIVE.raw=all;MDLIVE.n=Object.keys(all).length;MDLIVE.miss=miss;MDLIVE.sup=sup;MDLIVE.unk=unk;\n"
    "  MDLIVE.at=Date.now();MDLIVE.err='';MDLIVE.src=ok.join(' + ');\n",
    "  const lbl=[];if(ok.indexOf('form')>=0)lbl.push('form');\n"
    "  if(gok)lbl.push('sheet'+(gok<gtot?' '+gok+'/'+gtot+' day tabs':''));\n"
    "  MDLIVE.raw=all;MDLIVE.n=Object.keys(all).length;MDLIVE.miss=miss;MDLIVE.sup=sup;MDLIVE.unk=unk;\n"
    "  MDLIVE.offd=offd;MDLIVE.at=Date.now();MDLIVE.err='';MDLIVE.src=lbl.join(' + ');\n",
    'mdpFeedLoad: compact source label')

edit(
    "  try{localStorage.setItem(MDP_FEED.cache,JSON.stringify({at:MDLIVE.at,raw:all,n:MDLIVE.n,\n"
    "   miss:miss,sup:sup,unk:unk,src:MDLIVE.src,warn:MDLIVE.warn}));}catch(e){}\n",
    "  try{localStorage.setItem(MDP_FEED.cache,JSON.stringify({at:MDLIVE.at,raw:all,n:MDLIVE.n,\n"
    "   miss:miss,sup:sup,unk:unk,offd:offd,src:MDLIVE.src,warn:MDLIVE.warn}));}catch(e){}\n",
    'mdpFeedLoad: cache the wrong-day count')

# 9. restore + init
edit(
    "  if(d&&d.raw&&d.at){MDLIVE.raw=d.raw;MDLIVE.at=d.at;MDLIVE.n=d.n||0;MDLIVE.miss=d.miss||0;MDLIVE.sup=d.sup||0;\n"
    "   MDLIVE.unk=d.unk||0;MDLIVE.src=d.src||'';MDLIVE.warn=d.warn||'';}}catch(e){}\n",
    "  if(d&&d.raw&&d.at){MDLIVE.raw=d.raw;MDLIVE.at=d.at;MDLIVE.n=d.n||0;MDLIVE.miss=d.miss||0;MDLIVE.sup=d.sup||0;\n"
    "   MDLIVE.unk=d.unk||0;MDLIVE.offd=d.offd||0;MDLIVE.src=d.src||'';MDLIVE.warn=d.warn||'';}}catch(e){}\n",
    'mdpFeedRestore: restore the wrong-day count')

edit(
    "let MDLIVE={raw:{},at:0,n:0,miss:0,sup:0,unk:0,err:'',warn:'',src:'',busy:0,blk:[],blkAt:0,blkErr:'',blkSrc:'',blkJunk:0};\n",
    "let MDLIVE={raw:{},at:0,n:0,miss:0,sup:0,unk:0,offd:0,err:'',warn:'',src:'',busy:0,blk:[],blkAt:0,blkErr:'',blkSrc:'',blkJunk:0};\n",
    'MDLIVE: wrong-day count')

# 10. chip
edit(
    "  +(MDLIVE.unk?' \u00b7 '+MDLIVE.unk+' reason'+(MDLIVE.unk===1?'':'s')+' read as Other':'')\n",
    "  +(MDLIVE.unk?' \u00b7 '+MDLIVE.unk+' reason'+(MDLIVE.unk===1?'':'s')+' read as Other':'')\n"
    "  +(MDLIVE.offd?' \u00b7 '+MDLIVE.offd+' row'+(MDLIVE.offd===1?'':'s')+' in another day tab':'')\n",
    'mdpFeedChip: show wrong-day rows')

edit(
    "  +(two?' \u00b7 sources: '+MDLIVE.src:' \u00b7 source: Google Form responses')\n",
    "  +(two?' \u00b7 sources: '+MDLIVE.src:' \u00b7 source: Google Form responses')\n"
    "  +(MDLIVE.offd?' \u00b7 '+MDLIVE.offd+' row'+(MDLIVE.offd===1?'':'s')+' named a different campaign day than its tab and were read under the tab they sit in':'')\n",
    'mdpFeedChip: explain the wrong-day rows')

# 11. blocked-UC card: the Blockers tab is still read, and a missing tab says so
edit(
    "   if(o.badHdr)throw new Error('the UC column is missing');\n",
    "   // Google answers a tab it cannot find with the first tab's rows, which have no UC column, so\n"
    "   // both a renamed tab and a tab missing its header land here. Cached rows then describe a tab\n"
    "   // that is no longer in the workbook, so they are dropped rather than shown as a current log.\n"
    "   if(o.badHdr){\n"
    "    MDLIVE.blk=[];MDLIVE.blkAt=0;MDLIVE.blkSrc='none';MDLIVE.blkJunk=0;\n"
    "    try{localStorage.removeItem(MDP_FEED.cache+'.blk');}catch(e){}\n"
    "    throw new Error('the '+MDP_FEED.gridBlock+' tab is missing, renamed or has no UC column');\n"
    "   }\n",
    'mdpFeedLoad: name the Blockers tab and drop a dead cache')

edit(
    " const B=mdpBlkScope(),T=mdpBlkTot(B);\n"
    " if(!B.length){\n"
    "  if(MDLIVE.blkErr)return none(",
    " const B=mdpBlkScope(),T=mdpBlkTot(B);\n"
    " if(!B.length){\n"
    "  if(MDLIVE.blkSrc==='none')return none('The workbook behind the district sheet has no <b>'+esc(MDP_FEED.gridBlock)+'</b> tab, so no UC-level block log is collected: each day tab\\u2019s reason column still records why teams fell short. Add the tab, press <b>Copy Blockers header</b> on the card above and paste it into cell A1, then read the sheet again. The district feed itself is unaffected.');\n"
    "  if(MDLIVE.blkErr)return none(",
    'mdpBlockCard: say when the tab is not in the workbook')

# 12. caption under the buttons
edit(
    "The <b>district intake sheet</b> is the workbook behind the shared district sheet: in the <b>Live</b> tab it already carries one row per district per campaign day, so a district only types its time of update and its counts, and in the <b>Blockers</b> tab it takes the UC log \u2014 district, day, UC, a fixed reason and cause, teams affected and awaited, the blocked and cleared times \u2014 so a district can file either offline in the Sheets app. Neither tab has a free-text column.",
    "The <b>district intake sheet</b> is the workbook behind the shared district sheet: it files one tab per campaign day, <b>Day-1st</b> to <b>Day-5th</b>, and each tab already carries one row per district for that day, so a district only types its time of update and its counts and can file offline in the Sheets app; the <b>Blockers</b> tab still takes the UC log \u2014 district, day, UC, a fixed reason and cause, teams affected and awaited, the blocked and cleared times. No tab carries a free-text column.",
    'caption: day tabs alongside the Blockers tab')


def main():
    cfg, vs = dashpatch.load_variants()
    v = next(x for x in vs if x.rel == 'index.html')
    if 'gridTabs:' in v.text:
        print('nothing to do')
        return
    for old, new, note in EDITS:
        v.require(v.text.count(old) == 1, 'anchor %r found %d times' % (note, v.text.count(old)))
        v.text = v.text.replace(old, new, 1)
        v.changes.append(note)
    dashpatch.assert_crlf(v)
    dashpatch.write_variants([v])
    print('PATCHED index.html %+d chars, %d edits' % (v.delta(), len(EDITS)))


if __name__ == '__main__':
    main()
